"""Логика приветствия в зависимости от времени суток (вариант 14).

    с 04:00 до 11:00 -> Доброе утро
    с 11:00 до 18:00 -> Добрый день
    с 18:00 до 22:00 -> Добрый вечер
    с 22:00 до 04:00 -> Доброй ночи
"""

# Границы задаются как (начало часа, приветствие); диапазоны не
# пересекаются, поэтому достаточно последовательной проверки.
TIME_RANGES = (
    (4, 11, "Доброе утро"),
    (11, 18, "Добрый день"),
    (18, 22, "Добрый вечер"),
)
NIGHT_GREETING = "Доброй ночи"


def greeting_for_hour(hour):
    """Возвращает текст приветствия для заданного часа (0-23).

    Некорректные значения (например, из-за сбоя источника времени)
    не приводят к падению - час просто приводится к диапазону 0-23.
    """
    hour = hour % 24

    for start, end, greeting in TIME_RANGES:
        if start <= hour < end:
            return greeting

    return NIGHT_GREETING
